import { execFile } from 'node:child_process'
import type { ChildProcess } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { availableParallelism } from 'node:os'
import { fileURLToPath } from 'node:url'
import { analyzeLevel } from '../src/engine/forced.ts'
import type { Quality } from '../src/engine/forced.ts'
import { generateLevel } from '../src/engine/generator.ts'
import { flowsFor, toGrid } from '../src/engine/levels.ts'
import type { Level } from '../src/engine/types.ts'

type Row = { rows: number; cols: number; seed: number; mode: 'unique' | 'open' }

// Levels 1-2 are the unique tutorial boards; the rest are open mode, where unique boards are welcome
// too (every flow forced) and only the forced-flow quota decides.
const TABLE: Row[] = [
  { rows: 5, cols: 5, seed: 101, mode: 'unique' },
  { rows: 6, cols: 6, seed: 202, mode: 'unique' },
  ...[
    [7, 7], [8, 8], [9, 9], [10, 9], [10, 10], [11, 10], [11, 11], [12, 11],
    [12, 12], [13, 13], [14, 13], [14, 14], [15, 15],
  ].map(([rows, cols], i) => ({ rows, cols, seed: 1000 * (i + 3), mode: 'open' as const })),
]

const SEED_TRIES = 600
const CANDIDATE_MS = 5000 // a candidate whose proofs take longer is skipped

/** Lane `lane` of `lanes` tries seeds lane, lane + lanes, ... so lanes never repeat each other's work. */
function build(row: Row, n: number, lane: number, lanes: number): { level: Level; quality: Quality | null } {
  const flows = flowsFor(row.rows, row.cols)
  for (let offset = lane; offset < SEED_TRIES; offset += lanes) {
    const level = generateLevel({
      rows: row.rows,
      cols: row.cols,
      flows,
      seed: row.seed + offset,
      id: `level-${n}`,
      name: `Level ${n}`,
      mode: row.mode,
      budget: { candidates: 1, candidateMs: CANDIDATE_MS }, // one raw candidate per seed; the quota check below judges it
    })
    if (row.mode === 'unique') return { level, quality: null }
    const deadline = Date.now() + CANDIDATE_MS
    const quality = analyzeLevel(level, { exhaustive: true, deadline })
    if (quality.met) return { level, quality }
  }
  throw new Error(`no level meeting the quota for ${row.rows}x${row.cols}`)
}

type Entry = { id: string; name: string; grid: string[]; forced: string[] }

const CACHE = new URL('./.cache/', import.meta.url)
const cacheFile = (n: number) => new URL(`level-${n}.json`, CACHE)

/** Builds one level and returns its data entry (runs in a child process). */
function buildEntry(n: number, lane: number, lanes: number): Entry {
  const { level, quality } = build(TABLE[n - 1], n, lane, lanes)
  const forced = quality?.forced ?? level.pairs.map((p) => p.color)
  return { id: level.id, name: level.name, grid: toGrid(level), forced }
}

/** One lane in a child process; resolves with its level, or rejects when it is killed or finds none. */
function runLane(n: number, lane: number, lanes: number, children: ChildProcess[]): Promise<Entry> {
  return new Promise((resolve, reject) => {
    const script = fileURLToPath(import.meta.url)
    const args = [script, '--level', String(n), String(lane), String(lanes)]
    const child = execFile('node', args, { maxBuffer: 1 << 24 }, (error, stdout) => {
      if (error) reject(error)
      else resolve(JSON.parse(stdout) as Entry)
    })
    children.push(child)
  })
}

/** All cores search different seeds for the same level; the first level found wins. */
async function buildInParallel(n: number): Promise<Entry> {
  const lanes = Math.max(1, availableParallelism() - 1)
  const children: ChildProcess[] = []
  const attempts = Array.from({ length: lanes }, (_, lane) => runLane(n, lane, lanes, children))
  try {
    return await Promise.any(attempts)
  } finally {
    for (const child of children) child.kill()
  }
}

async function main(): Promise<void> {
  mkdirSync(CACHE, { recursive: true })
  const entries: Entry[] = []
  for (let n = 1; n <= TABLE.length; n++) {
    const file = cacheFile(n)
    const cached = existsSync(file)
    const entry = cached ? (JSON.parse(readFileSync(file, 'utf8')) as Entry) : await buildInParallel(n)
    if (!cached) writeFileSync(file, JSON.stringify(entry))
    entries.push(entry)
    console.log(`${entry.name.padEnd(9)} ${TABLE[n - 1].rows}x${TABLE[n - 1].cols}  forced ${entry.forced.join('')}${cached ? '  (cached)' : ''}`)
  }

  const body = `// Generated by scripts/generate-levels.ts. Do not edit by hand.
import type { LevelData } from './levels.ts'

export const LEVEL_DATA: LevelData[] = ${JSON.stringify(entries, null, 2)}
`
  writeFileSync(new URL('../src/engine/levels.data.ts', import.meta.url), body)
  console.log(`wrote ${entries.length} levels`)
}

const flag = process.argv.indexOf('--level')
if (flag >= 0) {
  const [n, lane, lanes] = process.argv.slice(flag + 1, flag + 4).map(Number)
  process.stdout.write(JSON.stringify(buildEntry(n, lane, lanes)))
} else await main()
